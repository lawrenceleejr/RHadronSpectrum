"""Closed spatial Wilson paths at a site, their O_h orbits, and evaluation on a link field.

A path is a tuple of steps d in {+-1, +-2, +-3} meaning a unit step along +-(x, y, z).
"""
import numpy as np

from ..backend import get_xp
from ..gauge.field import SITE_AXIS, dag, mul
from ..groups.oh import elements


def step_vec(d):
    v = np.zeros(3, dtype=int)
    v[abs(d) - 1] = np.sign(d)
    return v


def vec_step(v):
    (k,) = np.nonzero(v)[0]
    return int((k + 1) * np.sign(v[k]))


def rotate(path, R):
    return tuple(vec_step(R @ step_vec(d)) for d in path)


def reverse(path):
    return tuple(-d for d in reversed(path))


def is_closed(path):
    return not np.any(sum(step_vec(d) for d in path))


def canonical(path):
    """(key, flipped): key = min(path, reverse(path)); flipped = True if path is the reversed one."""
    r = reverse(path)
    return (path, False) if path <= r else (r, True)


def orbit(path):
    """Distinct paths (modulo reversal) generated by O_h from ``path``; and the signed-permutation
    action: for each group element g, a list perm[g][k] = (m, flipped) with g . path_k = path_m
    (reversed if flipped)."""
    G = elements()
    keys = []
    for R in G:
        k, _ = canonical(rotate(path, R))
        if k not in keys:
            keys.append(k)
    index = {k: i for i, k in enumerate(keys)}
    action = []
    for R in G:
        row = []
        for k in keys:
            m, fl = canonical(rotate(k, R))
            row.append((index[m], fl))
        action.append(row)
    return keys, action


def rep_matrices(action, n, c_sign):
    """Matrices T(g) on the orbit space: T(g) e_k = s e_m with s = c_sign if flipped else +1.
    c_sign = -1 for the anti-Hermitian (C = -) operator, +1 for the Hermitian (C = +) one."""
    mats = []
    for row in action:
        T = np.zeros((n, n))
        for k, (m, fl) in enumerate(row):
            T[m, k] = c_sign if fl else 1.0
        mats.append(T)
    return mats


def roll3(f, off):
    """g(x) = f(x + off) for a site field [t, z, y, x, ...], off = (dx, dy, dz)."""
    xp = get_xp(f)
    shifts = tuple(-int(off[m]) for m in range(3) if off[m] != 0)
    axes = tuple(SITE_AXIS[m] for m in range(3) if off[m] != 0)
    if not shifts:
        return f
    return xp.roll(f, shifts, axis=axes)


def path_field(V, path):
    """P(x) = product of links along ``path`` starting at x, for the spatial links V[0..2]."""
    xp = get_xp(V)
    off = np.zeros(3, dtype=int)
    P = None
    for d in path:
        mu = abs(d) - 1
        if d > 0:
            L = roll3(V[mu], off)
            off[mu] += 1
        else:
            off[mu] -= 1
            L = dag(roll3(V[mu], off))
        P = L.copy() if P is None else mul(P, L)
    return P


# Gluelump operator shapes (start = end = source site).  Planar and non-planar loops.
SHAPES = {
    "plaq": (1, 2, -1, -2),                    # 1x1 plaquette with a corner at x
    "rect": (1, 1, 2, -1, -1, -2),             # 2x1 rectangle, corner at x
    "chair": (1, 2, -1, 3, -2, -3),            # bent 6-link (chair) loop, 3D
    "twist": (1, 2, 3, -1, -2, -3),            # 6-link twisted loop through 3 dirs (no planar part)
    "lplaq": (1, 2, 3, -2, -1, -3),            # closed L-shaped 3D loop
}
